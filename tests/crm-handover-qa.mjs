import assert from 'node:assert/strict';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import {crmPriorities} from '../lib/crm-priorities.ts';
import {buildPlan,applyPlan,day} from '../lib/erp-engine.ts';
import CRM from '../app/erp-crm.tsx';
import CRMPriorities from '../app/crm-priorities.tsx';
let passed=0;
const check=(v,label)=>{assert.ok(v,label);passed++;};
const base={company:'Hagadol',date:day(),created:'2026-10-24T00:00:00Z',amount:0,status:'Open',version:0};
const deal={...base,id:'example-deal',type:'deal',crm:true,crmStage:'New',status:'New',name:'Example drilling deal',owner:'Example owner',customer:'Example client'};
const activity=(id,due,extra={})=>({...base,id,type:'task',name:id,crm:true,owner:'Example owner',due,...extra});
const records=[deal,activity('old','2020-01-01'),activity('today',day()),activity('future','2099-01-01'),activity('done',day(),{status:'Done'}),activity('undated',''),activity('eos',day(),{crm:false,eos:true})];
const snapshot=JSON.stringify(records),groups=crmPriorities(records,day());
check(groups.overdue.map(r=>r.id).join()==='old','Only overdue pending CRM work is overdue');
check(groups.today.map(r=>r.id).join()==='today','Today excludes completed and EOS work');
check(groups.upcoming.map(r=>r.id).join()==='future','Future activities stay upcoming');
check(groups.undated.map(r=>r.id).join()==='undated','Undated records remain visible for review');
check(JSON.stringify(records)===snapshot,'Priorities do not mutate records');
const state={records:[deal],journal:[],audit:[]};
const lossInput={action:'stage',id:deal.id,status:'Lost',expectedVersion:0,lostReason:'Client postponed project',followUpDate:'2099-01-01',requestId:'loss-test'};
const plan=buildPlan(lossInput,state);
check(plan.writes.length===2,'Loss and follow up are in the same atomic plan');
check(plan.entries.length===0,'CRM loss does not post to finance');
const task=plan.writes.find(r=>r.type==='task');
check(task.company==='Hagadol'&&task.dealId===deal.id&&task.owner===deal.owner,'Follow up retains company, deal and owner');
check(task.due==='2099-01-01'&&task.lossFollowUp===true,'Requested follow up is preserved');
check(plan.writes.find(r=>r.type==='deal').status==='Lost','Loss bypasses technical survey requirements');
assert.throws(()=>buildPlan({...lossInput,lostReason:''},state),/reason/);passed++;
assert.throws(()=>buildPlan({...lossInput,followUpDate:'2020-01-01'},state),/today/);passed++;
assert.throws(()=>buildPlan({...lossInput,expectedVersion:9},state));passed++;
const next=applyPlan(state,plan),lost=next.records.find(r=>r.id===deal.id);
const repeated=buildPlan({...lossInput,expectedVersion:lost.version,requestId:'loss-repeat'},next);
check(repeated.writes.filter(r=>r.type==='task').length===0,'Repeated loss does not duplicate an open follow up');
assert.throws(()=>buildPlan({...lossInput,expectedVersion:lost.version,followUpDate:'2099-02-01'},next),/already exists/);passed++;
check(buildPlan({...lossInput,followUpDate:''},state).writes.length===1,'Follow up is optional');
const wm={...deal,id:'wm-deal',company:'WMK'};
check(buildPlan({...lossInput,id:wm.id,requestId:'wm-loss'},{...state,records:[wm]}).writes.every(r=>r.company==='WMK'),'WMK loss stays entirely within WMK');
const props={state:{...state,records},company:'Hagadol',tab:'Pipeline',busy:false,act:async()=>false,onDirty:()=>{},importContacts:()=>{}};
const html=renderToStaticMarkup(React.createElement(CRM,props));
check(html.includes('Today’s priorities')&&html.includes('Due today')&&html.includes('Upcoming'),'Pipeline has the agreed priority sections');
const contacts=renderToStaticMarkup(React.createElement(CRM,{...props,tab:'Contacts'}));
check(!contacts.includes('Today’s priorities'),'Directory stays focused');
const priorities=renderToStaticMarkup(React.createElement(CRMPriorities,{records,busy:false,onOpen:()=>{},onComplete:async()=>{}}));
check(priorities.includes('Complete today')&&!priorities.includes('Complete done'),'Priority actions cover pending work only');
const detail=renderToStaticMarkup(React.createElement(CRM,{...props,initialDetail:deal.id}));
check(detail.includes('<dialog')&&detail.includes('Today’s priorities'),'Drawer preserves the board behind it');
console.log(JSON.stringify({passed,failed:0,syntheticData:true,browserInteractionsTested:false,liveProductionTouched:false}));
