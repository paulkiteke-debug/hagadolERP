import assert from 'node:assert/strict';
import {parseBiginPreviewCSV,reviewBiginCSV} from '../lib/crm-import-preview.ts';
let passed=0;
const check=(v,label)=>{assert.ok(v,label);passed++;};
const header='Contact Id,Contact Name,First Name,Last Name,Company Name,Email,Phone,Mobile,Job Title,Business Unit';
const first='zcrm_123456789012345,Emma Example,Emma,Example,Actual Company,emma@example.invalid,+256700001001,,Engineer,Hagadol';
const second='zcrm_123456789012346,Second Person,Second,Person,Other Company,second@example.invalid,+256700001002,,,Hagadol';
const text=header+'\r\n'+first+'\r\n'+second;
const result=reviewBiginCSV(text,'Hagadol',[]);
check(result.rows.length===2,'No example row is inserted');
check(result.rows[0].sourceId==='zcrm_123456789012345','First source identity remains intact');
check(result.rows[0].name==='Emma Example','Full Contact Name is preserved');
check(result.rows[0].customerCompany==='Actual Company','Company Name is the customer company');
check(result.rows[0].jobTitle==='Engineer','Only Job Title supplies job title');
check(result.rows[1].jobTitle==='','Last Name is never inferred as job title');
check(result.rows[0].phone==='+256700001001','First phone stays on the first row');
check(result.rows[1].phone==='+256700001002','Second phone stays on the second row');
check(result.valid===2&&result.needsReview===0&&result.duplicates===0,'Counts are calculated from the file');
check(result.rows[0].row===2&&result.rows[1].row===3,'Physical record row numbers include the header');
const duplicate=reviewBiginCSV(text+'\n'+first.replace('123456789012345','123456789012347'),'Hagadol',[]);
check(duplicate.duplicates===2&&duplicate.rows.length===3,'Duplicates flagged on both rows and retained separately');
const repeatedId=reviewBiginCSV(text+'\n'+first,'Hagadol',[]);
check(repeatedId.duplicates===2,'Repeated source IDs are flagged');
const sourceCopy=JSON.stringify(result.rows.map(r=>r.source));
check(JSON.stringify(result.rows.map(r=>r.source))===sourceCopy,'Source values remain present on the row');
const existing=[{id:'existing',company:'Hagadol',type:'contact',name:'Existing',email:'emma@example.invalid',biginContactId:'zcrm_999999999999999'}];
check(reviewBiginCSV(text,'Hagadol',existing).duplicates===1,'Existing same business email is flagged');
check(reviewBiginCSV(text,'Hagadol',existing.map(r=>({...r,company:'WMK'}))).duplicates===0,'Another business does not cause a duplicate');
check(reviewBiginCSV(text,'Hagadol',existing.map(r=>({...r,email:'',phone:'0700001001'}))).duplicates===1,'Uganda local and international phone formats match');
const known=reviewBiginCSV(text,'Hagadol',[{...existing[0],biginContactId:'zcrm_123456789012345'}]);
check(known.rows[0].warnings.some(w=>w.includes('already exists')),'Previously imported identity is marked for update review');
check(reviewBiginCSV(text,'WMK',[]).valid===0,'Business Unit mismatch is not treated as valid');
check(reviewBiginCSV(text.replaceAll(',Hagadol',','),'Hagadol',[]).needsReview===2,'Blank business assignment requires review');
check(parseBiginPreviewCSV('Contact Id,Contact Name\nzcrm_123456789012345,"Name, with comma"')[0]['Contact Name']==='Name, with comma','Quoted comma does not shift columns');
check(parseBiginPreviewCSV('Contact Id,Contact Name\nzcrm_123456789012345,"Name with ""quotes"""')[0]['Contact Name']==='Name with "quotes"','Escaped quotes stay intact');
check(parseBiginPreviewCSV('Contact Id,Contact Name\nzcrm_123456789012345,"Two\nLines"')[0]['Contact Name']==='Two\nLines','Quoted line breaks remain on their own record');
check(parseBiginPreviewCSV('\ufeff'+text).length===2,'UTF8 BOM is handled');
for(const [input,message] of [[header+'\nwrong','different number'],['x,x\n1,2','duplicate'],['a,b\n"open,quote','unclosed'],['a,b\n1,2','source ID'],['a,b','at least one']]){
 assert.throws(()=>reviewBiginCSV(input,'Hagadol',[]),new RegExp(message));passed++;
}
assert.throws(()=>reviewBiginCSV(text,'Group',[]),/Choose/);passed++;
check(reviewBiginCSV('Company Id,Company Name,Business Unit\nzcrm_123456789012345,Example Ltd,Hagadol','Hagadol',[]).kind==='Companies','Company exports detected');
check(reviewBiginCSV('Sale Id,Sale Name,Business Unit\nzcrm_123456789012345,Example Sale,Hagadol','Hagadol',[]).kind==='Deals','Deal exports detected');
check(reviewBiginCSV('Task Id,Subject,Business Unit\nzcrm_123456789012345,Example Task,Hagadol','Hagadol',[]).kind==='Activities','Task exports detected');
console.log(JSON.stringify({passed,failed:0,syntheticData:true,readOnly:true,liveProductionTouched:false}));
